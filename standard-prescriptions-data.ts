export function getFallbackStandardPrescriptions(
  category: string = 'all',
  diseaseQuery: string = '',
  language: string = 'en'
): { data: StandardPrescriptionData; sources: GroundingSource[] } {
  const isHi = language === 'hi';
  const query = diseaseQuery.trim().toLowerCase();

  let filtered = standardGolwalaPrescriptions;

  // Filter by category if not 'all'
  if (category && category !== 'all') {
    filtered = filtered.filter(
      (p) => p.category.toLowerCase() === category.toLowerCase() || p.severityLevel.toLowerCase() === category.toLowerCase()
    );
  }

  // Filter by query if provided
  if (query) {
    filtered = standardGolwalaPrescriptions.filter(
      (p) =>
        p.diseaseName.toLowerCase().includes(query) ||
        (p.hindiName && p.hindiName.toLowerCase().includes(query)) ||
        p.category.toLowerCase().includes(query) ||
        p.severityLevel.toLowerCase().includes(query) ||
        p.rxMedications.some(
          (m) =>
            m.genericSalt.toLowerCase().includes(query) ||
            m.brandExamples.toLowerCase().includes(query) ||
            m.drugCategory.toLowerCase().includes(query)
        )
    );
  }

  // If query yielded no match, return all so the user is never left with an empty screen
  if (filtered.length === 0) {
    filtered = standardGolwalaPrescriptions;
  }

  const data: StandardPrescriptionData = {
    lastUpdated: 'October 2026',
    sourceTextbook: "Golwala's Medicine for Students & Reference Prescriber (25th Edition & Standard Clinical Protocols)",
    prescriptions: filtered,
    totalConditionsCount: standardGolwalaPrescriptions.length,
    disclaimer: isHi
      ? 'यह स्टैंडर्ड प्रिस्क्रिप्शन मेडिकल विद्यार्थियों, पीजी रेजिडेंट्स और चिकित्सकों के शैक्षणिक व संदर्भ उपयोग हेतु गोलवाला प्रेस्क्राइबर व मानक राष्ट्रीय दिशानिर्देशों के अनुसार तैयार किया गया है। रोगी के गुर्दे, यकृत की स्थिति व एलर्जी की जांच अनिवार्य है।'
      : 'These standard clinical prescriptions are compiled in accordance with Golwala Medicine for Students / Golwala Prescriber and standard national clinical pharmacology guidelines for healthcare professionals and medical students. Always calibrate dosages based on renal function, pregnancy status, and drug interactions.',
  };

  const sources: GroundingSource[] = [
    {
      title: "Golwala's Medicine for Students: A Reference Book for the Practitioner (Dr. Aspi Golwala & Dr. Sharukh Golwala)",
      url: 'https://www.jaypeebrothers.com',
    },
    {
      title: 'National Medical Commission (NMC) Standard Treatment Guidelines & Generic Prescribing Mandate',
      url: 'https://www.nmc.org.in',
    },
    {
      title: 'Indian Council of Medical Research (ICMR) Standard Treatment Workflows',
      url: 'https://main.icmr.nic.in',
    },
    {
      title: 'National Formulary of India (NFI) & CDSCO Approved Dosage Guidelines',
      url: 'https://cdsco.gov.in',
    },
  ];

  return { data, sources };
}
